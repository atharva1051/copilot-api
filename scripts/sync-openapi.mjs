import { readFileSync, writeFileSync } from "node:fs"

const source = new URL("../docs/openapi.yaml", import.meta.url)
const target = new URL("../src/routes/openapi/spec.ts", import.meta.url)

const yaml = readFileSync(source, "utf8")
const output = `// GENERATED by scripts/sync-openapi.mjs from docs/openapi.yaml. Do not edit by hand.\nexport const openapiYaml = ${JSON.stringify(yaml)}\n`

if (process.argv.includes("--check")) {
  let current = ""
  try {
    current = readFileSync(target, "utf8")
  } catch {
    // missing file counts as out of date
  }
  if (current !== output) {
    console.error(
      "src/routes/openapi/spec.ts is out of date. Run: npm run docs:sync",
    )
    process.exit(1)
  }
  console.log("openapi spec is in sync")
} else {
  writeFileSync(target, output)
  console.log("wrote src/routes/openapi/spec.ts")
}
